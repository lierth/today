// IdleForParse reads the nanoseconds number out of `ioreg -c IOHIDSystem`
// output. The line looks like:
//
//	"HIDIdleTime" = 1234567890
//
// A missing line returns ok=false, which the caller treats as "not idle".
func IdleForParse(out string) (time.Duration, bool) {
	for _, line := range strings.Split(out, "\n") {
		line = strings.TrimSpace(line)
		if !strings.HasPrefix(line, `"HIDIdleTime"`) {
			continue
		}
		_, value, ok := strings.Cut(line, "=")
		if !ok {
			continue
		}
		ns, err := strconv.ParseInt(strings.TrimSpace(value), 10, 64)
		if err != nil || ns < 0 {
			return 0, false
		}
		return time.Duration(ns), true
	}
	return 0, false
}

// OnAC reads the power source out of `pmset -g batt` output. The line reads
// `Now drawing from 'AC Power'` (or `'Battery Power'`). Unknown returns false:
// a background download on battery is exactly what the rule forbids.
func OnAC(out string) bool {
	return strings.Contains(out, "'AC Power'") || strings.Contains(out, "AC Power")
}

// IdleEligible combines the two checks the brief calls "闲时": the person has
// been away for at least `threshold` and the Mac is on mains power.
func IdleEligible(idle time.Duration, haveIdle bool, ac bool, threshold time.Duration) bool {
	if threshold <= 0 {
		threshold = IdleFor
	}
	return haveIdle && ac && idle >= threshold
}

// ReadIdle runs ioreg. It is a variable so a test can fake it.
var ReadIdle = func() (time.Duration, bool) {
	out, err := exec.Command("ioreg", "-c", "IOHIDSystem", "-d", "4").Output()
	if err != nil {
		return 0, false
	}
	return IdleForParse(string(out))
}

// ReadAC runs pmset.
var ReadAC = func() bool {
	out, err := exec.Command("pmset", "-g", "batt").Output()
	if err != nil {
		return false
	}
	return OnAC(string(out))
}

// BundleID and VersionFromPlist read the two fields the installer checks. It
// accepts the XML plist mygo writes; a binary plist is refused, because a
// bundled Info.plist is XML in practice and parsing binary here would mean a
// dependency.
func VersionFromPlist(data []byte) (bundleID, version, shortVersion string) {
	text := string(data)
	bundleID = plistValue(text, "CFBundleIdentifier")
	version = plistValue(text, "CFBundleShortVersionString")
	if version == "" {
		version = plistValue(text, "CFBundleVersion")
	}
	shortVersion = version
	return bundleID, version, shortVersion
}

// plistValue finds <key>name</key> followed by <string>value</string>.
func plistValue(text, key string) string {
	i := strings.Index(text, "<key>"+key+"</key>")
	if i < 0 {
		return ""
	}
	rest := text[i+len(key)+11:]
	start := strings.Index(rest, "<string>")
	if start < 0 {
		return ""
	}
	rest = rest[start+len("<string>"):]
	end := strings.Index(rest, "</string>")
	if end < 0 {
		return ""
	}
	return strings.TrimSpace(rest[:end])
}

// InstallPlan is what the replacement script will do, computed before anything
// is touched so the caller can log it.
type InstallPlan struct {
	CurrentApp string // /Applications/Today.app
	NewApp     string // staged Today.app inside the extraction dir
	OldApp     string // CurrentApp + ".old"
	Script     string // the shell script path
	PID        int
	// StartedMarker is written by the new version once it is up; the script
	// waits for it so a crash on launch is rolled back instead of accepted.
	StartedMarker string
}

// BundleInside finds the .app directory inside an unzipped release. `ditto -x
// -k` writes a top-level Today.app; a nested layout is refused.
func BundleInside(dir string) (string, error) {
	entries, err := os.ReadDir(dir)
	if err != nil {
		return "", err
	}
	for _, e := range entries {
		if e.IsDir() && strings.HasSuffix(e.Name(), ".app") {
			return filepath.Join(dir, e.Name()), nil
		}
	}
	return "", fmt.Errorf("解压后找不到 .app：%s", dir)
}

// InstallScript is the shell script that swaps the bundle once this process is
// gone. It is generated, not shipped, so the paths are exact.
//
// The script:
//  1. waits up to `waitSeconds` for the old PID to exit;
//  2. moves the current bundle aside, moves the new one in;
//  3. starts the new bundle;
//  4. if that fails, restores the old bundle and starts it.
//
// It writes progress to its own log so a failure after the app quit is
// diagnosable.
func InstallScript(plan InstallPlan, waitSeconds int) string {
	if waitSeconds <= 0 {
		waitSeconds = 30
	}
	app := shQuote(plan.CurrentApp)
	old := shQuote(plan.OldApp)
	newApp := shQuote(plan.NewApp)
	marker := shQuote(plan.StartedMarker)
	pid := plan.PID
	return fmt.Sprintf(`#!/bin/sh
# Generated by Today %s. Replaces the bundle after the old process exits.
LOG="$(dirname "$0")/install.log"
exec >>"$LOG" 2>&1
echo "== $(date) install start, pid %d"
i=0
while kill -0 %d 2>/dev/null; do
  i=$((i+1))
  if [ "$i" -ge %d ]; then
    echo "old process did not exit after %ds, aborting"
    exit 1
  fi
  sleep 1
done
rm -rf %s
if ! mv %s %s; then
  echo "could not move the current app aside"
  open %s
  exit 1
fi
if ! mv %s %s; then
  echo "could not move the new app in, rolling back"
  mv %s %s
  open %s
  exit 1
fi
# "open" returns 0 as soon as the system hands the launch off, even if the new
# app dies on its first line. The new version writes a marker when it is really
# up; wait for it, and roll back when it never appears.
rm -f %s
if ! open %s; then
  echo "new app did not start, rolling back"
  rm -rf %s
  mv %s %s
  open %s
  exit 1
fi
i=0
while [ ! -f %s ]; do
  i=$((i+1))
  if [ "$i" -ge %d ]; then
    echo "new app never signalled startup, rolling back"
    rm -rf %s
    mv %s %s
    open %s
    exit 1
  fi
  sleep 1
done
echo "== done"
`,
		VersionNumber, pid, pid, waitSeconds, waitSeconds,
		old, app, old, app,
		newApp, app,
		old, app, app,
		marker, app,
		app, old, app, app,
		marker, waitSeconds,
		app, old, app, app,
	)
}

// VersionNumber is the build's version, injected by ldflags.
var VersionNumber = "dev"

func shQuote(s string) string {
	return "'" + strings.ReplaceAll(s, "'", `'\''`) + "'"
}

// CleanupOldBundle removes Today.app.old when it is older than a grace period.
// The new version calls it at startup: the old bundle must survive long enough
// for the new one to prove it starts.
func CleanupOldBundle(appPath string, minAge time.Duration) error {
	old := appPath + ".old"
	st, err := os.Stat(old)
	if err != nil {
		return nil
	}
	if time.Since(st.ModTime()) < minAge {
		return nil
	}
	return os.RemoveAll(old)
}

// VerifyDesignatedRequirement refuses a bundle signed by a different identity
// than the one running. Without it an attacker who can write the download
// cache could swap in their own signed app, and macOS would happily launch it
// because the signature is valid — the requirement check is what makes the
// signature mean "the same publisher as the version being replaced".
//
// Both sides come from `codesign -d -r- <app>`; an ad-hoc build has a
// requirement of the form `designated => cdhash H"..."`, which changes with
// every build and therefore cannot be compared across versions. In that case
// the check is skipped with a warning: there is nothing stable to pin.
func VerifyDesignatedRequirement(newApp, currentApp string) error {
	if currentApp == "" {
		return nil // todayd or a test: no bundle to compare with
	}
	current, err := designatedRequirement(currentApp)
	if err != nil {
		return fmt.Errorf("读不到当前 app 的签名要求：%w", err)
	}
	if isAdhoc(current) {
		// An ad-hoc requirement pins a cdhash that changes with every build;
		// there is nothing stable to compare. `codesign --verify` still runs
		// below, so a corrupted or unsigned bundle is refused.
		return codesignVerify(newApp, "")
	}
	// The real check: codesign re-evaluates the new bundle's signature against
	// the *current* app's designated requirement. Comparing the two texts
	// (the previous implementation) only proves they look alike; this proves
	// the new bundle actually satisfies the identity.
	return codesignVerify(newApp, current)
}

// codesignVerify runs `codesign --verify --deep --strict` on app, optionally
// with an explicit requirement.
func codesignVerify(app, requirement string) error {
	args := []string{"--verify", "--deep", "--strict"}
	if requirement != "" {
		args = append(args, "-R="+requirement)
	}
	args = append(args, app)
	out, err := exec.Command("codesign", args...).CombinedOutput()
	if err != nil {
		msg := strings.TrimSpace(string(out))
		if msg == "" {
			msg = err.Error()
		}
		return fmt.Errorf("新版本的签名校验失败：%s", msg)
	}
	return nil
}

func designatedRequirement(app string) (string, error) {
	out, err := exec.Command("codesign", "-d", "-r-", app).CombinedOutput()
	text := strings.TrimSpace(string(out))
	if err != nil && text == "" {
		return "", err
	}
	for _, line := range strings.Split(text, "\n") {
		if strings.HasPrefix(strings.TrimSpace(line), "designated =>") {
			return strings.TrimSpace(strings.TrimPrefix(strings.TrimSpace(line), "designated =>")), nil
		}
	}
	// An unsigned bundle prints nothing parseable.
	if text == "" {
		return "", errors.New("app 没有签名")
	}
	return text, nil
}

// isAdhoc reports whether a requirement pins a cdhash instead of an identity.
func isAdhoc(req string) bool {
	return strings.Contains(req, "cdhash") && !strings.Contains(req, "identifier ")
}

// StartedMarkerPath is where a freshly launched version writes its "I am up"
// marker: <data>/run/started. The installer's script waits for it.
func StartedMarkerPath() string {
	root := dataRoot()
	return filepath.Join(root, "run", "started")
}

// dataRoot is ~/.today, mirroring internal/datahome (which cannot be imported
// here without a cycle: datahome is about paths, release about bundles).
func dataRoot() string {
	if v := strings.TrimSpace(os.Getenv("TODAY_HOME")); v != "" {
		return v
	}
	home, err := os.UserHomeDir()
	if err != nil || home == "" {
		return ".today"
	}
	return filepath.Join(home, ".today")
}

// WriteStartedMarker tells a waiting installer that this version is up. It is
// called from the host's ready(); a failure is logged by the caller.
func WriteStartedMarker() error {
	path := StartedMarkerPath()
	if err := os.MkdirAll(filepath.Dir(path), 0o700); err != nil {
		return err
	}
	return os.WriteFile(path, []byte(VersionNumber+"\n"), 0o600)
}
